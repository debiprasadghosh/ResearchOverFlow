"""Seeded simulations for the neocortex–thalamus–hippocampus section.
N1  place-cell nerve recovers environment topology (Curto–Itskov setting)
N2  thalamic gating = cover selection: Betti numbers vs fraction of cells gated in
N3  replay as offline repair: local pairwise (Kaczmarz) replay vs quadratic optimum
N4  impossible-loop (wormhole) maze: per-segment corrections under each repair policy
Run: python3 trio_numerics.py  -> trio_results.json, fig_nerve.png, fig_replay.png
"""
import itertools, json, math
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

SEED = 20261021
rng = np.random.default_rng(SEED)
EPS = np.finfo(float).eps
R = {}

def rank_R(A):
    if A.size == 0: return 0
    s = np.linalg.svd(A, compute_uv=False)
    return int((s > max(A.shape) * EPS * s[0]).sum()) if s[0] > 0 else 0

def betti_from_codes(codes):
    """Betti numbers (b0, b1) over F2 of the 2-skeleton generated by codewords.
    b0 by union-find; rank of the triangle boundary by bitset column reduction
    (planar complexes here have no torsion, so F2 and real Betti numbers agree)."""
    V = sorted({i for c in codes for i in c}); vi = {v: i for i, v in enumerate(V)}
    E, T = set(), set()
    for c in codes:
        c = sorted(c)
        E.update(itertools.combinations(c, 2))
        if len(c) >= 3: T.update(itertools.combinations(c, 3))
    parent = list(range(len(V)))
    def find(x):
        while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for a_, b_ in E:
        ra, rb = find(vi[a_]), find(vi[b_])
        if ra != rb: parent[ra] = rb
    b0 = len({find(i) for i in range(len(V))})
    cyc = len(E) - len(V) + b0                     # dim Z1 = |E| - rank D
    Ei = {e: i for i, e in enumerate(sorted(E))}
    piv = {}; rB = 0
    for a_, b_, c_ in T:
        if rB == cyc: break                        # boundaries already fill all cycles
        r = (1 << Ei[(a_, b_)]) | (1 << Ei[(b_, c_)]) | (1 << Ei[(a_, c_)])
        while r:
            p = r.bit_length() - 1
            if p in piv: r ^= piv[p]
            else: piv[p] = r; rB += 1; break
    return b0, cyc - rB

# environment: annulus inner radius 0.2, outer 0.5, centred at origin; control: disc radius 0.5
def sample_env(hole, m=60):
    xs = np.linspace(-0.5, 0.5, m); X, Y = np.meshgrid(xs, xs); P = np.c_[X.ravel(), Y.ravel()]
    r = np.hypot(P[:, 0], P[:, 1])
    keep = (r <= 0.5) & ((r >= 0.2) if hole else True)
    return P[keep]

def place_centres(n, hole):
    out = []
    while len(out) < n:
        p = rng.uniform(-0.5, 0.5, 2); r = math.hypot(*p)
        if r <= 0.5 and (r >= 0.2 if hole else True): out.append(p)
    return np.array(out)

def codes_for(P, C, rho):
    d = np.linalg.norm(P[:, None, :] - C[None, :, :], axis=2) < rho
    return {tuple(np.flatnonzero(row)) for row in d if row.any()}

# ---------- N1 + N2 ---------------------------------------------------------
def n1_n2():
    P_ann, P_disc = sample_env(True), sample_env(False)
    rows = []
    grid = [(n, rho) for n in [30, 60, 120] for rho in [0.06, 0.10, 0.15]] + [(40, 0.25), (40, 0.35)]
    for n, rho in grid:
            ok_ann = ok_disc = 0; trials = 30
            for _ in range(trials):
                C = place_centres(n, True)
                ok_ann += betti_from_codes(codes_for(P_ann, C, rho)) == (1, 1)
                C = place_centres(n, False)
                ok_disc += betti_from_codes(codes_for(P_disc, C, rho)) == (1, 0)
            rows.append(dict(n=n, rho=rho, trials=trials, mean_cells_per_point=round(n * math.pi * rho ** 2 / (math.pi * (0.25 - 0.04)), 1),
                             annulus_correct=ok_ann / trials, disc_correct=ok_disc / trials))
    R["N1"] = rows
    # N2: gating a fraction of cells into the cover
    gate = []
    n, rho = 120, 0.12
    for keep in [1.0, 0.75, 0.5, 0.3, 0.15]:
        ok = 0; b1s = []; trials = 30
        for _ in range(trials):
            C = place_centres(n, True)
            C = C[rng.random(n) < keep]
            b = betti_from_codes(codes_for(P_ann, C, rho)) if len(C) else (0, 0)
            ok += b == (1, 1); b1s.append(b[1])
        gate.append(dict(keep=keep, cells=round(n * keep), correct=ok / trials, mean_b1=float(np.mean(b1s)), max_b1=int(max(b1s))))
    R["N2"] = gate
    # figure: left = under-coverage instance; right = first large-field instance showing the typical failure
    fig, ax = plt.subplots(1, 2, figsize=(6.4, 3.2)); th = np.linspace(0, 2 * np.pi, 200)
    C_left = place_centres(40, True)
    for attempt in range(1, 50):
        C_right = place_centres(40, True)
        if betti_from_codes(codes_for(P_ann, C_right, 0.35)) == (1, 0): break
    R["N1_fig_attempts_right"] = attempt
    for a, rho, C in zip(ax, [0.10, 0.35], [C_left, C_right]):
        for c in C: a.plot(c[0] + rho * np.cos(th), c[1] + rho * np.sin(th), lw=0.3, color="#4a78b5", alpha=0.6)
        for rr in (0.2, 0.5): a.plot(rr * np.cos(th), rr * np.sin(th), color="k", lw=1.2)
        b = betti_from_codes(codes_for(P_ann, C, rho))
        a.set_title(f"n = 40, ρ = {rho}: nerve (β₀, β₁) = {b}", fontsize=9); a.set_aspect("equal"); a.axis("off")
    plt.tight_layout(); plt.savefig("fig_nerve.png", dpi=200); plt.close()

# ---------- N3: replay as local repair --------------------------------------
def n3():
    # a 6-cycle (loop corridor) with a 4-edge tree attached: events = vertices, transitions = edges
    edges = [(i, (i + 1) % 6) for i in range(6)] + [(0, 6), (6, 7), (3, 8), (8, 9)]
    edges = [tuple(sorted(e)) for e in edges]; n = 10; m = len(edges)
    D = np.zeros((m, n))
    for i, (u, v) in enumerate(edges): D[i, u] = -1; D[i, v] = 1
    z = np.zeros(m); cyc = {(0, 1): 1, (1, 2): 1, (2, 3): 1, (3, 4): 1, (4, 5): 1, (0, 5): -1}
    for i, e in enumerate(edges): z[i] = cyc.get(e, 0)
    assert np.allclose(z @ D, 0)
    s_true = rng.normal(0, 1, n)
    rows = []; traces = {}
    T = 60000
    for kappa in [0.0, 0.5, 1.0, 2.0]:
        g = D @ s_true + kappa * z / (z @ z)          # zᵀg = κ exactly
        Pg = D @ np.linalg.lstsq(D, g, rcond=None)[0]  # quadratic optimum (unit weights)
        out = {}
        for mode in ["constant", "annealed"]:
            s = np.zeros(n); errs = []
            for t in range(1, T + 1):
                e = rng.integers(m); u, v = edges[e]
                eta = 0.5 if mode == "constant" else min(0.5, 50.0 / t)
                r = (s[v] - s[u]) - g[e]
                s[u] += eta * r / 2; s[v] -= eta * r / 2
                if t % 200 == 0: errs.append(np.linalg.norm(D @ s - Pg))
            out[mode] = errs
            traces[(kappa, mode)] = errs
        floor = float(np.sqrt(np.mean(np.square(out["constant"][-100:]))))
        rows.append(dict(kappa=kappa, constant_floor=floor, annealed_final=float(out["annealed"][-1]),
                         optimum_residual=float(np.linalg.norm(g - Pg))))
    R["N3"] = dict(cycle_len=6, tree_edges=4, replay_events=T, rows=rows)
    plt.figure(figsize=(6.2, 3.3))
    tt = np.arange(200, T + 1, 200)
    for kappa, c in zip([0.0, 1.0, 2.0], ["#2c7fb8", "#d95f0e", "#7a0177"]):
        plt.semilogy(tt, np.maximum(traces[(kappa, "constant")], 1e-17), color=c, lw=1, label=f"κ={kappa}, constant plasticity")
        plt.semilogy(tt, np.maximum(traces[(kappa, "annealed")], 1e-17), color=c, lw=1.6, ls="--", label=f"κ={kappa}, annealed")
    plt.xlabel("replay events"); plt.ylabel("‖Ds − Pg‖  (distance to quadratic optimum)")
    plt.legend(frameon=False, fontsize=7, ncol=2); plt.tight_layout(); plt.savefig("fig_replay.png", dpi=200); plt.close()

# ---------- N4: impossible-loop maze predictions ----------------------------
def n4():
    # four corridors around a loop; odometry lengths (m) and reliability weights w ∝ 1/variance
    names = ["A (2 m, textured)", "B (4 m, plain)", "C (2 m, textured)", "D (4 m, plain, wormhole)"]
    w = np.array([4.0, 1.0, 4.0, 1.0]); z = np.ones(4); kappa = 1.0     # loop fails to close by 1 m
    cq = -kappa * (z / w) / (z @ (z / w))
    j = int(np.argmin(w)); cs = np.zeros(4); cs[j] = -kappa * z[j]          # tie: B and D, argmin picks B
    R["N4"] = dict(segments=names, weights=w.tolist(), kappa=kappa, quadratic=cq.tolist(),
                   sparse_one_edge=cs.tolist(), tie_note="B and D tie in cost; a one-edge policy is not unique here",
                   quadratic_cost=float(cq @ (w * cq)), sparse_cost=float(cs @ (w * cs)))

if __name__ == "__main__":
    for f in (n1_n2, n3, n4): f(); print(f.__name__, "done", flush=True)
    R["seed"] = SEED; R["numpy"] = np.__version__
    json.dump(R, open("trio_results.json", "w"), indent=1)
